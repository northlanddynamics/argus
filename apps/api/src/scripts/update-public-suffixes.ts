/**
 * Regenerates `observables/public-suffixes.ts` from the Public Suffix List's ICANN section, with
 * international rules as punycode, the way domains are stored.
 *
 *   bun src/scripts/update-public-suffixes.ts [path-or-url]
 *
 * Defaults to https://publicsuffix.org/list/public_suffix_list.dat.
 */
import { domainToASCII } from "node:url";

const source = process.argv[2] ?? "https://publicsuffix.org/list/public_suffix_list.dat";
const text = /^https?:/.test(source) ? await (await fetch(source)).text() : await Bun.file(source).text();
const begin = text.indexOf("\n", text.indexOf("===BEGIN ICANN DOMAINS==="));
const icann = text.slice(begin, text.indexOf("===END ICANN DOMAINS==="));
const rules = icann
  .split("\n")
  .map((line) => line.trim().split(/\s/)[0] ?? "")
  .filter((line) => line && !line.startsWith("//"))
  .map((rule) => {
    const prefix = rule.match(/^[!*.]*/)![0];
    const name = rule.slice(prefix.length);
    const ascii = domainToASCII(name);
    if (!ascii) throw new Error(`Can't read the rule ${rule}`);
    return prefix + ascii;
  });
if (rules.length < 1000) throw new Error(`Only ${rules.length} rules: is that the Public Suffix List?`);

const out = `/**
 * The ICANN section of the Public Suffix List (https://publicsuffix.org/), with international rules
 * as punycode. Generated by \`scripts/update-public-suffixes.ts\`; don't edit by hand.
 *
 * This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy of
 * the MPL was not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.
 */
export const PUBLIC_SUFFIX_RULES = ${JSON.stringify(rules.join(" "))};
`;
await Bun.write(new URL("../observables/public-suffixes.ts", import.meta.url), out);
console.log(`Wrote ${rules.length} rules`);
